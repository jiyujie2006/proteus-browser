#!/usr/bin/env node

import assert from 'node:assert/strict';
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import {
  createArtifactLicenseBundle,
  validateGeneratedChromiumCredits,
  verifyArtifactLicenseBundle,
} from '../scripts/artifact-licenses.mjs';
import { packageEngine } from '../scripts/package-engine.mjs';

const root = mkdtempSync(join(tmpdir(), 'proteus-artifact-licenses-'));
let passed = 0;

function test(label, fn) {
  try {
    fn();
    passed += 1;
    process.stdout.write(`ok - ${label}\n`);
  } catch (error) {
    process.stderr.write(`not ok - ${label}: ${error.stack || error}\n`);
    process.exitCode = 1;
  }
}

function generatedCredits({ placeholder = false, sample = false } = {}) {
  const products = [];
  for (let index = 0; index < 30; index += 1) {
    products.push(
      '<div class="product">\n'
      + `<span class="title">Dependency ${index}</span>\n`
      + '<span class="homepage"><a href="https://example.invalid/">homepage</a></span>\n'
      + '<label class="show" tabindex="0"><input type="checkbox" hidden></label>\n'
      + '<div class="license"><pre>'
      + 'Example license terms. '.repeat(140)
      + '</pre></div>\n'
      + '</div>\n',
    );
  }
  return Buffer.from(
    '<!-- Generated by licenses.py; do not edit. -->\n'
    + '<!doctype html>\n<html>\n<head><meta charset="utf-8">\n'
    + '<title>Credits</title></head><body>\n'
    + '<!-- Chromium <3s the following projects -->\n'
    + (sample ? 'This is sample credits page. Set generate_about_credits=true.\n' : '')
    + products.join('')
    + (placeholder ? '{{entries}}\n' : '')
    + '</body></html>\n',
    'utf8',
  );
}

function makeOutput(name = 'out') {
  const out = join(root, name);
  mkdirSync(join(out, 'gen', 'components', 'resources'), { recursive: true });
  writeFileSync(join(out, 'chrome'), 'engine\n');
  writeFileSync(
    join(out, 'gen', 'components', 'resources', 'about_credits.html'),
    generatedCredits(),
  );
  return out;
}

function makePackageInputs(name) {
  const dependencyLock = join(root, `${name}-dependencies.json`);
  const effectiveGnArgs = join(root, `${name}-effective-args.json`);
  const toolchainLock = join(root, `${name}-toolchain.json`);
  writeFileSync(dependencyLock, '{"kind":"dependency-lock-fixture"}\n');
  writeFileSync(effectiveGnArgs, '{"kind":"effective-args-fixture"}\n');
  writeFileSync(toolchainLock, '{"kind":"toolchain-lock-fixture"}\n');
  return { dependencyLock, effectiveGnArgs, toolchainLock };
}

try {
  test('generated Chromium credits require the pinned real template shape', () => {
    const audit = validateGeneratedChromiumCredits(generatedCredits());
    assert.equal(audit.entries, 30);
    assert.match(audit.sha256, /^[0-9a-f]{64}$/u);
    assert.ok(audit.size >= 64 * 1024);
  });

  test('generated Chromium credits require the M150 generator banner', () => {
    const withoutBanner = generatedCredits().subarray(
      '<!-- Generated by licenses.py; do not edit. -->\n'.length,
    );
    assert.throws(
      () => validateGeneratedChromiumCredits(withoutBanner),
      /pinned generated credits template/u,
    );
  });

  test('padded Chromium sample credits are rejected', () => {
    assert.throws(
      () => validateGeneratedChromiumCredits(generatedCredits({ sample: true })),
      /sample credits/u,
    );
  });

  test('unexpanded generated-credit templates are rejected', () => {
    assert.throws(
      () => validateGeneratedChromiumCredits(
        generatedCredits({ placeholder: true }),
      ),
      /template placeholders/u,
    );
  });

  const out = makeOutput();
  const bundle = join(root, 'license-bundle');
  mkdirSync(bundle);
  let manifest;
  test('artifact license bundle is deterministic and build-derived', () => {
    manifest = createArtifactLicenseBundle({
      bundleDir: bundle,
      outDir: out,
      platform: 'linux-x64',
    });
    assert.equal(manifest.documentKind, 'artifact-license-bundle');
    assert.equal(manifest.credits.entries, 30);
    assert.deepEqual(
      manifest.files.map(({ path }) => path),
      [
        'LICENSES/Proteus-Apache-2.0.txt',
        'LICENSES/Chromium-BSD-3-Clause.txt',
        'LICENSES/Chromium-Third-Party-Credits.html',
        'NOTICE',
      ],
    );
    assert.deepEqual(
      verifyArtifactLicenseBundle({
        bundleDir: bundle,
        manifest: readFileSync(
          join(bundle, 'LICENSES', 'artifact-license-manifest.json'),
        ),
        platform: 'linux-x64',
      }).files,
      4,
    );
  });

  test('verification rehashes license bytes', () => {
    const chromiumLicense = join(
      bundle,
      'LICENSES',
      'Chromium-BSD-3-Clause.txt',
    );
    const original = readFileSync(chromiumLicense);
    writeFileSync(chromiumLicense, 'tampered\n');
    assert.throws(
      () => verifyArtifactLicenseBundle({
        bundleDir: bundle,
        manifest,
        platform: 'linux-x64',
      }),
      /digest mismatch/u,
    );
    writeFileSync(chromiumLicense, original);
  });

  test('verification rejects unknown manifest fields', () => {
    assert.throws(
      () => verifyArtifactLicenseBundle({
        bundleDir: bundle,
        manifest: { ...manifest, approved: true },
        platform: 'linux-x64',
      }),
      /missing or unknown fields/u,
    );
  });

  test('macOS license bundle requires matching credits from both architectures', () => {
    const macX64 = makeOutput('mac-x64');
    const macArm64 = makeOutput('mac-arm64');
    const universalOut = join(root, 'mac-universal');
    mkdirSync(universalOut);
    const macBundle = join(root, 'mac-license-bundle');
    mkdirSync(macBundle);
    const macManifest = createArtifactLicenseBundle({
      bundleDir: macBundle,
      outDir: universalOut,
      creditsOutDirs: [macX64, macArm64],
      platform: 'macos-universal',
    });
    assert.deepEqual(
      macManifest.credits.architectures,
      ['x86_64', 'arm64'],
    );
  });

  test('different macOS architecture credits fail closed', () => {
    const macX64 = makeOutput('mac-mismatch-x64');
    const macArm64 = makeOutput('mac-mismatch-arm64');
    const credits = join(
      macArm64,
      'gen',
      'components',
      'resources',
      'about_credits.html',
    );
    writeFileSync(
      credits,
      Buffer.concat([generatedCredits(), Buffer.from('<!-- mismatch -->\n')]),
    );
    const universalOut = join(root, 'mac-mismatch-universal');
    mkdirSync(universalOut);
    const macBundle = join(root, 'mac-mismatch-bundle');
    mkdirSync(macBundle);
    assert.throws(
      () => createArtifactLicenseBundle({
        bundleDir: macBundle,
        outDir: universalOut,
        creditsOutDirs: [macX64, macArm64],
        platform: 'macos-universal',
      }),
      /differ between x86_64 and arm64/u,
    );
  });

  if (process.platform !== 'win32') {
    test('credits source cannot be replaced by a symlink', () => {
      const unsafeOut = join(root, 'unsafe-out');
      mkdirSync(
        join(unsafeOut, 'gen', 'components', 'resources'),
        { recursive: true },
      );
      const outside = join(root, 'outside-credits.html');
      writeFileSync(outside, generatedCredits());
      symlinkSync(
        outside,
        join(
          unsafeOut,
          'gen',
          'components',
          'resources',
          'about_credits.html',
        ),
      );
      const unsafeBundle = join(root, 'unsafe-bundle');
      mkdirSync(unsafeBundle);
      assert.throws(
        () => createArtifactLicenseBundle({
          bundleDir: unsafeBundle,
          outDir: unsafeOut,
          platform: 'linux-x64',
        }),
        /ordinary non-symlink file/u,
      );
    });
  }

  if (process.platform === 'linux') {
    test('complete engine manifest covers the license bundle and credits', () => {
      const packageOut = makeOutput('package-out');
      const packageBundle = join(root, 'packaged-engine');
      const records = makePackageInputs('package');
      const completeManifest = packageEngine({
        outDir: packageOut,
        bundleDir: packageBundle,
        ...records,
        outDirRelative: 'out/Proteus',
        platform: 'linux-x64',
        runtimeDependencies: ['chrome'],
      });
      const paths = new Set(completeManifest.entries.map(({ path }) => path));
      for (const path of [
        'BUILD-CONTRACT.json',
        'LICENSES/artifact-license-manifest.json',
        'LICENSES/Chromium-Third-Party-Credits.html',
        'LICENSES/Chromium-BSD-3-Clause.txt',
        'LICENSES/Proteus-Apache-2.0.txt',
        'NOTICE',
        'PACKAGE-RECORD.json',
        'chrome',
      ]) {
        assert.ok(paths.has(path), `missing complete-tree entry ${path}`);
      }
    });
  }
} finally {
  rmSync(root, { force: true, recursive: true });
}

if (!process.exitCode) {
  process.stdout.write(`${passed} artifact-license tests passed\n`);
}
